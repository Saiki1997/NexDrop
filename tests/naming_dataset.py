def case(cid, category, file, expect, *, naming=None, page=None, wrong=(), v2_only=(), note=""):
    return {
        "id": cid,
        "category": category,
        "file": file,
        "expect": expect,
        "naming": dict(naming or {}),
        "page": page,  # (url, {meta name: content}) of the file's own page, if the crawler fetched one
        "wrong": list(wrong),
        "v2_only": list(v2_only),
        "note": note,
    }


def page(url, **meta):
    return (url, {k.replace("_", ":", 1) if k.startswith(("og_", "twitter_")) else k: v for k, v in meta.items()})


