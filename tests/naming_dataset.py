"""Labelled naming cases for measuring smart naming (V1 vs V2).

Each case is the metadata a site adapter hands the naming engine for one file, and the title a
person would want for it. The metadata mirrors what the adapters in engine/vendor produce: forum
posts give a first-line caption and a thread title, Bunkr/GoFile/Cyberdrop give an album name and
the uploader's filename, social sites give a caption, image hosts give per-image titles.

Labels were written from the naming spec, before either engine was run on them:
  expect   the wanted title (no number, no extension); ORIGINAL means "keep the original name"
  wrong    titles that would be a wrong association (another post, an advert, the site's name)
  v2_only  metadata keys only V2 adapters supply (V1 adapters never sent them)

No real media or private data is used: names and captions are made up in the style of each site.
"""

from __future__ import annotations

