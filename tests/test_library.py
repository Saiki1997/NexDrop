"""3.1 media library: History import, moved and renamed files, metadata, thumbnails, exact
duplicates and similar images, videos and audio. Media is generated by ffmpeg in the test."""

import json
import shutil
import subprocess
import sys
import tempfile
import time
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "desktop"))

import library  # noqa: E402
from job_store import JobStore  # noqa: E402

FFMPEG = library.tool("ffmpeg")
HAVE_FF = bool(FFMPEG and library.tool("ffprobe"))


def ff(*args):
    subprocess.run([FFMPEG, "-v", "error", "-y", *args], check=True)


@unittest.skipUnless(HAVE_FF, "ffmpeg and ffprobe are needed")
class Library(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = Path(tempfile.mkdtemp())
        media = cls.tmp / "downloads"
        (media / "site-a").mkdir(parents=True)
        (media / "site-b").mkdir(parents=True)
        cls.media = media
        # one picture, the same picture smaller and re-encoded, and a different picture
        ff("-f", "lavfi", "-i", "testsrc2=size=640x480", "-frames:v", "1", str(media / "site-a" / "pic.png"))
        ff("-i", str(media / "site-a" / "pic.png"), "-vf", "scale=320:240", "-q:v", "8", str(media / "site-b" / "pic-small.jpg"))
        ff("-f", "lavfi", "-i", "mandelbrot=size=640x480", "-frames:v", "1", str(media / "site-a" / "other.png"))
        # a video and the same video re-encoded at a lower size; a different video of the same length
        ff("-f", "lavfi", "-i", "testsrc=duration=6:size=320x240:rate=15", "-pix_fmt", "yuv420p", str(media / "site-a" / "clip.mp4"))
        ff("-i", str(media / "site-a" / "clip.mp4"), "-vf", "scale=160:120", "-crf", "35", str(media / "site-b" / "clip-low.mp4"))
        ff("-f", "lavfi", "-i", "mandelbrot=size=320x240:rate=15", "-t", "6", "-pix_fmt", "yuv420p", str(media / "site-b" / "fractal.mp4"))
        # a sound with a changing loudness, the same as a lower bitrate mp3, and a different sound
        ff("-f", "lavfi", "-i", "sine=frequency=440:duration=12", "-af", "volume='0.2+0.8*abs(sin(t*1.7))':eval=frame",
           str(media / "site-a" / "tone.wav"))
        ff("-i", str(media / "site-a" / "tone.wav"), "-b:a", "64k", str(media / "site-b" / "tone.mp3"))
        ff("-f", "lavfi", "-i", "anoisesrc=duration=12:amplitude=0.5", "-af", "volume='0.2+0.8*abs(cos(t*0.6))':eval=frame",
           str(media / "site-b" / "noise.wav"))
        # an exact copy under another name, on another site
        shutil.copy(media / "site-a" / "other.png", media / "site-b" / "renamed-copy.png")

        cls.jobs = cls.tmp / "jobs.sqlite"
        store = JobStore(cls.jobs)
        job = store.start_job(["https://site-a.test/album/1"], str(media))
        identity = {"creator": "alice", "album": "Holiday", "post_title": "Day one"}
        for name in ("pic.png", "other.png", "clip.mp4", "tone.wav"):
            path = media / "site-a" / name
            store.note(job, {"url": f"https://cdn.site-a.test/{name}", "host": "site-a.test", "name": name, "destination": str(path),
                             "event": "success", "bytes_total": path.stat().st_size,
                             "naming": {"original": name, "identity": identity}})
        store.finish_job(job, "completed")
        store.close()

        cls.db = cls.tmp / "library.sqlite"
        cls.conn = library.connect(cls.db)
        cls.synced = library.sync_history(cls.conn, cls.jobs)
        cls.scan = library.scan_roots(cls.conn, [str(media)])
        cls.work = library.work(cls.conn, 120, cls.tmp / "thumbs")

    @classmethod
    def tearDownClass(cls):
        cls.conn.close()
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def row(self, name):
        return self.conn.execute("SELECT * FROM files WHERE name = ?", (name,)).fetchone()

    def test_history_files_keep_their_source(self):
        self.assertEqual(self.synced, 4)
        row = self.row("pic.png")
        self.assertEqual((row["host"], row["creator"], row["album"], row["title"]), ("site-a.test", "alice", "Holiday", "Day one"))
        self.assertEqual(row["source"], "https://site-a.test/album/1")
        self.assertEqual(self.scan["added"], 6)  # the other files were found by the folder scan

    def test_metadata_is_read(self):
        self.assertEqual(self.work["left"], 0)
        pic = self.row("pic.png")
        self.assertEqual((pic["width"], pic["height"]), (640, 480))
        clip = self.row("clip.mp4")
        self.assertAlmostEqual(clip["duration"], 6.0, delta=0.2)
        self.assertIn("h264", clip["codec"])
        tone = self.row("tone.mp3")
        self.assertGreater(tone["bitrate"], 0)
        self.assertAlmostEqual(tone["duration"], 12.0, delta=0.3)

    def test_thumbnails_are_small_files_in_the_cache(self):
        for name in ("pic.png", "clip.mp4"):
            thumb = self.tmp / "thumbs" / self.row(name)["thumb"]
            self.assertTrue(thumb.is_file(), name)
            out = subprocess.run([library.tool("ffprobe"), "-v", "error", "-show_entries", "stream=width", "-of", "csv=p=0", str(thumb)],
                                 capture_output=True, text=True).stdout.strip()
            self.assertLessEqual(int(out), 256)
        self.assertEqual(self.row("tone.wav")["thumb"], "")

    def test_exact_copy_under_another_name_and_site(self):
        result = library.groups(self.conn, {"kind": "exact"})
        names = [sorted(f["name"] for f in g["files"]) for g in result["groups"]]
        self.assertEqual(names, [["other.png", "renamed-copy.png"]])
        group = result["groups"][0]
        self.assertTrue(group["crossSite"] or group["hosts"] == ["site-a.test"])
        self.assertTrue(group["names"])
        self.assertEqual(group["reason"], "exact")

    def test_similar_images_videos_and_audio(self):
        result = library.groups(self.conn, {"kind": "similar"})
        found = {g["reason"]: sorted(f["name"] for f in g["files"]) for g in result["groups"]}
        self.assertEqual(found.get("similar-image"), ["pic-small.jpg", "pic.png"])
        self.assertEqual(found.get("similar-video"), ["clip-low.mp4", "clip.mp4"])
        self.assertEqual(found.get("similar-audio"), ["tone.mp3", "tone.wav"])
        self.assertEqual(len(result["groups"]), 3)  # the exact copies, the fractal and the noise are not listed here

    def test_search_filter_sort_and_group(self):
        result = library.query(self.conn, {"kind": "image", "sort": "largest"})
        self.assertEqual(result["total"], 4)
        sizes = [i["size"] for i in result["items"]]
        self.assertEqual(sizes, sorted(sizes, reverse=True))
        self.assertEqual([i["name"] for i in library.query(self.conn, {"text": "holiday"})["items"]].sort(), None)
        self.assertEqual(library.query(self.conn, {"creator": "alice"})["total"], 4)
        one = result["items"][0]["path"]
        self.assertEqual([i["path"] for i in library.query(self.conn, {"paths": [one]})["items"]], [one])  # one job's files
        self.assertEqual(library.query(self.conn, {"paths": []})["total"], 0)
        grouped = library.query(self.conn, {"group": "host"})
        self.assertIn("site-a.test", [g["key"] for g in grouped["groups"]])
        facets = library.facets(self.conn)
        self.assertEqual(facets["creators"], ["alice"])
        self.assertEqual(facets["kinds"]["video"], 3)

    def test_storage_overview(self):
        result = library.storage(self.conn, [str(self.media)])
        self.assertEqual(result["files"], 10)
        self.assertTrue(result["disks"] and result["disks"][0]["free"] > 0)
        self.assertEqual({k["key"] for k in result["byKind"]}, {"image", "video", "audio"})


class MovedFiles(unittest.TestCase):
    def test_moved_and_renamed_files_are_followed_and_missing_ones_marked(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            (base / "a").mkdir()
            for i in range(3):
                (base / "a" / f"f{i}.bin").write_bytes(bytes([i]) * (200_000 + i))
            conn = library.connect(base / "lib.sqlite")
            library.scan_roots(conn, [str(base / "a")])
            library.prepare_quick(conn, time.monotonic() + 10)
            first = {r["name"]: r["id"] for r in conn.execute("SELECT id, name FROM files")}
            (base / "a" / "sub").mkdir()
            (base / "a" / "f0.bin").rename(base / "a" / "sub" / "renamed.bin")
            (base / "a" / "f1.bin").unlink()
            result = library.scan_roots(conn, [str(base / "a")])
            self.assertEqual((result["relinked"], result["missing"], result["added"]), (1, 1, 0))
            row = conn.execute("SELECT * FROM files WHERE id = ?", (first["f0.bin"],)).fetchone()
            self.assertEqual(row["name"], "renamed.bin")
            self.assertEqual(conn.execute("SELECT missing FROM files WHERE id = ?", (first["f1.bin"],)).fetchone()[0], 1)
            self.assertEqual(library.query(conn, {"missing": "only"})["total"], 1)
            conn.close()

    def test_partial_downloads_are_not_indexed(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            (base / "d").mkdir()
            for name in ("a.mp4.part", "a.mp4.part.seg1", "a.mp4.part.nxmeta", "NexDrop manifest job 1.nexdrop.json", "b.jpg"):
                (base / "d" / name).write_bytes(b"x")
            conn = library.connect(base / "lib.sqlite")
            library.scan_roots(conn, [str(base / "d")])
            self.assertEqual([r[0] for r in conn.execute("SELECT name FROM files")], ["b.jpg"])
            conn.close()


class Hashes(unittest.TestCase):
    def test_difference_hash(self):
        flat = bytes([100]) * 72
        self.assertEqual(library._dhash(flat), "0000000000000000")
        falling = bytes(255 - c * 20 for _ in range(8) for c in range(9))
        self.assertEqual(library._dhash(falling), "ffffffffffffffff")
        self.assertEqual(library._dhash(b"short"), "")

    def test_audio_distance_tolerates_a_small_shift(self):
        import random

        rng = random.Random(7)
        bits = "".join(rng.choice("01") for _ in range(600))
        self.assertEqual(library.audio_distance(bits, bits[3:]), 0.0)
        other = "".join("0" if c == "1" else "1" for c in bits)
        self.assertGreater(library.audio_distance(bits, other), library.SIMILAR_AUDIO * 3)


class CommandLine(unittest.TestCase):
    def test_query_over_stdin(self):
        with tempfile.TemporaryDirectory() as tmp:
            db = Path(tmp) / "lib.sqlite"
            run = subprocess.run([sys.executable, str(ROOT / "desktop" / "library.py"), "facets", str(db)], input="{}\n",
                                 capture_output=True, text=True, timeout=60)
            self.assertTrue(json.loads(run.stdout)["ok"], run.stderr)


